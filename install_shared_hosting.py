#!/usr/bin/env python3
"""Interactive, repeatable installer for cPanel/shared hosting.

It installs dependencies, writes a production .env, verifies the SQL database,
runs migrations/collectstatic, and creates (or resets) the administrator.
Passwords are requested with getpass and are never passed on the command line.
"""

from __future__ import annotations

import argparse
import getpass
import os
import re
import secrets
import shutil
import stat
import subprocess
import sys
from pathlib import Path
from urllib.parse import quote, urlparse

ROOT = Path(__file__).resolve().parent
ENV_FILE = ROOT / ".env"


def ask(label: str, default: str = "", secret: bool = False) -> str:
    suffix = f" [{default}]" if default else ""
    reader = getpass.getpass if secret else input
    value = reader(f"{label}{suffix}: ").strip()
    return value or default


def required(label: str, default: str = "", secret: bool = False) -> str:
    while True:
        value = ask(label, default, secret)
        if value:
            return value
        print("این مقدار الزامی است.")


def run(args: list[str], *, env: dict[str, str] | None = None) -> None:
    printable = " ".join(args)
    print(f"\n>>> {printable}")
    subprocess.run(args, cwd=ROOT, env=env, check=True)


def sql_url(engine: str, user: str, password: str, host: str, port: str, name: str) -> str:
    scheme = "mysql" if engine == "mysql" else "postgresql"
    return (
        f"{scheme}://{quote(user, safe='')}:{quote(password, safe='')}@"
        f"{host}:{port}/{quote(name, safe='')}"
    )


def env_value(value: str) -> str:
    # The project's dotenv reader supports quoted values but intentionally does
    # not process escapes. Installer inputs are constrained to single lines.
    if "\n" in value or "\r" in value:
        raise ValueError("مقادیر تنظیمات نمی‌توانند چندخطی باشند.")
    return value


def main() -> int:
    parser = argparse.ArgumentParser(description="نصب فایل‌مارکت روی هاست اشتراکی")
    parser.add_argument("--force", action="store_true", help="بازنویسی .env موجود (با تهیه نسخه پشتیبان)")
    parser.add_argument("--skip-deps", action="store_true", help="نصب نکردن requirements.txt")
    args = parser.parse_args()

    print("=" * 62)
    print(" نصب فایل‌مارکت: اتصال SQL، ساخت جداول و حساب مدیر")
    print("=" * 62)

    if ENV_FILE.exists() and not args.force:
        print("\nفایل .env از قبل وجود دارد؛ برای جلوگیری از حذف تنظیمات نصب متوقف شد.")
        print("برای نصب مجدد اجرا کنید: python install_shared_hosting.py --force")
        return 2

    engine = ask("نوع دیتابیس (mysql/postgresql)", "mysql").lower()
    while engine not in {"mysql", "postgresql"}:
        print("فقط mysql یا postgresql قابل قبول است.")
        engine = required("نوع دیتابیس").lower()

    db_host = required("هاست دیتابیس", "localhost")
    db_port = required("پورت دیتابیس", "3306" if engine == "mysql" else "5432")
    if not db_port.isdigit() or not 1 <= int(db_port) <= 65535:
        print("خطا: پورت دیتابیس نامعتبر است.")
        return 2
    db_name = required("نام کامل دیتابیس (با پیشوند cPanel)")
    db_user = required("نام کامل کاربر دیتابیس (با پیشوند cPanel)")
    db_password = required("رمز کاربر دیتابیس", secret=True)

    domain = required("دامنه سایت (مثلاً example.com)").lower()
    parsed_domain = urlparse(domain if "://" in domain else f"https://{domain}")
    hostname = parsed_domain.hostname
    if not hostname or not re.fullmatch(r"[a-z0-9.-]+", hostname):
        print("خطا: دامنه نامعتبر است.")
        return 2

    admin_user = required("نام کاربری مدیر", "admin")
    admin_email = required("ایمیل مدیر")
    admin_password = required("رمز مدیر (حداقل ۸ کاراکتر)", secret=True)
    confirm = required("تکرار رمز مدیر", secret=True)
    if admin_password != confirm:
        print("خطا: تکرار رمز مدیر یکسان نیست.")
        return 2
    if len(admin_password) < 8 or admin_password == "admin1234":
        print("خطا: رمز مدیر باید حداقل ۸ کاراکتر و غیر از admin1234 باشد.")
        return 2

    database_url = sql_url(engine, db_user, db_password, db_host, db_port, db_name)
    config = "\n".join(
        [
            "# Generated by install_shared_hosting.py",
            f"SECRET_KEY={secrets.token_urlsafe(64)}",
            "DEBUG=False",
            f"ALLOWED_HOSTS={env_value(hostname)},www.{env_value(hostname)}",
            f"CSRF_TRUSTED_ORIGINS=https://{env_value(hostname)},https://www.{env_value(hostname)}",
            "# Set to 1 only if the hosting support confirms its proxy overwrites X-Forwarded-Proto.",
            "BEHIND_HTTPS_PROXY=0",
            f"SITE_URL=https://{env_value(hostname)}",
            f"DATABASE_URL={env_value(database_url)}",
            "DB_CONN_MAX_AGE=0",
            "CACHE_URL=locmem://",
            "NOTIFICATIONS_ASYNC=1",
            "DJANGO_DATA_UPLOAD_MAX_MEMORY_SIZE=5242880",
            "DJANGO_FILE_UPLOAD_MAX_MEMORY_SIZE=1048576",
            "IMAGE_OPTIMIZATION_ENABLED=true",
            "IMAGE_OPTIMIZATION_MAX_DIMENSION=1600",
            "IMAGE_OPTIMIZATION_WEBP_QUALITY=80",
            "LOG_LEVEL=INFO",
            "",
        ]
    )

    if ENV_FILE.exists():
        backup = ROOT / ".env.before-install"
        shutil.copy2(ENV_FILE, backup)
        print(f"نسخه پشتیبان تنظیمات قبلی: {backup}")
    temporary = ROOT / ".env.installing"
    temporary.write_text(config, encoding="utf-8")
    os.chmod(temporary, stat.S_IRUSR | stat.S_IWUSR)
    temporary.replace(ENV_FILE)

    try:
        if not args.skip_deps:
            run([sys.executable, "-m", "pip", "install", "--disable-pip-version-check", "-r", "requirements.txt"])
        run([sys.executable, "manage.py", "check", "--database", "default"])
        run([sys.executable, "manage.py", "migrate", "--noinput"])
        run([sys.executable, "manage.py", "collectstatic", "--noinput"])
        child_env = os.environ.copy()
        child_env.update(
            {
                "ADMIN_DEFAULT_USERNAME": admin_user,
                "ADMIN_DEFAULT_EMAIL": admin_email,
                "ADMIN_DEFAULT_PASSWORD": admin_password,
            }
        )
        run(
            [sys.executable, "manage.py", "create_default_admin", "--reset-password"],
            env=child_env,
        )
        run([sys.executable, "manage.py", "check", "--deploy"])
    except subprocess.CalledProcessError as exc:
        print("\nنصب کامل نشد. پیام بالای این خط علت دقیق را نشان می‌دهد.")
        print("فایل .env ذخیره شده است؛ اطلاعات SQL را اصلاح و نصب را دوباره اجرا کنید.")
        return exc.returncode or 1

    print("\n" + "=" * 62)
    print("نصب با موفقیت کامل شد.")
    print(f"سایت: https://{hostname}/")
    print(f"ورود مدیر: https://{hostname}/admin/")
    print(f"نام کاربری مدیر: {admin_user}")
    print("اکنون Python App را در cPanel Restart کنید.")
    print("برای امنیت، فایل install_shared_hosting.py را از public_html خارج نگه دارید.")
    print("=" * 62)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
