"""خنثی‌سازی تزریق فرمول در خروجی‌های CSV.

سلولی که با ‎=‎، ‎+‎، ‎-‎، ‎@‎ یا Tab/CR شروع شود، وقتی فایل در
Excel/LibreOffice باز شود می‌تواند به‌جای متن، فرمول اجرا شود. داده‌های
کاربرساخته (نام کاربری، ایمیل، عنوان‌ها) وارد خروجی‌های CSV مدیریت
می‌شوند و مدیر فایل را روی سیستم خودش باز می‌کند؛ پس در مرز خروجی،
چنین سلول‌هایی با یک کوتیشن تکی خنثی می‌شوند (راهنمای OWASP برای
CSV Injection). مقدار نمایشی تقریباً دست‌نخورده می‌ماند و هیچ داده‌ای
در دیتابیس تغییر نمی‌کند.
"""

_FORMULA_PREFIXES = ('=', '+', '-', '@', '\t', '\r', '\n')


def csv_safe(value):
    """مقدار امن برای نوشتن در CSV؛ فقط رشته‌های مشکوک تغییر می‌کنند."""
    if not isinstance(value, str):
        return value
    stripped = value.lstrip(' \t\r\n')
    if stripped and stripped[0] in _FORMULA_PREFIXES:
        return "'" + value
    return value
